namespace Editor.Code;

// A position in a document: zero-based line and column (a char index into the line).
public readonly record struct TextPos(int Line, int Col) : IComparable<TextPos>
{
    public int CompareTo(TextPos other) => Line != other.Line ? Line.CompareTo(other.Line) : Col.CompareTo(other.Col);
    public static bool operator <(TextPos a, TextPos b) => a.CompareTo(b) < 0;
    public static bool operator >(TextPos a, TextPos b) => a.CompareTo(b) > 0;
}

// One script open in the code view: its lines, caret and selection, unsaved state and undo history.
// Tabs become four spaces when the file is read, so every column is one character wide.
public sealed class CodeDocument
{
    public const int IndentSize = 4;
    private const long GroupMilliseconds = 1200;   // typing within this long becomes one undo step

    private enum EditKind { None, Typing, Deleting, Other }
    private sealed record Snapshot(string Text, TextPos Caret);

    private readonly List<Snapshot> _undo = new();
    private readonly List<Snapshot> _redo = new();
    private EditKind _lastKind;
    private long _lastEditTicks;
    private string _savedText;

    public string Path { get; }
    public string Name => System.IO.Path.GetFileNameWithoutExtension(Path);
    public List<string> Lines { get; private set; }
    public string Newline { get; }
    public string? GeneratedFrom { get; }   // the .visualcode file this script is generated from, if any
    public bool ReadOnly => GeneratedFrom is not null;
    public bool Dirty => Text != _savedText;
    public int Version { get; private set; }   // changes on every edit, so views know to recolor and recheck

    public TextPos Caret { get; private set; }
    public TextPos? Anchor { get; private set; }   // the other end of the selection, when there is one
    public int PreferredCol { get; set; } = -1;    // column kept while moving up and down through short lines
    public float ScrollY { get; set; }
    public float ScrollX { get; set; }

    private CodeDocument(string path, string text, string newline, string? generatedFrom)
    {
        Path = path;
        Newline = newline;
        GeneratedFrom = generatedFrom;
        Lines = Split(text);
        _savedText = Text;
    }

    public static CodeDocument Load(string path)
    {
        string raw = File.Exists(path) ? File.ReadAllText(path) : "";
        string newline = raw.Contains("\r\n") ? "\r\n" : "\n";
        string text = Normalize(raw);

        string visual = System.IO.Path.ChangeExtension(path, ".visualcode");
        string? generatedFrom = File.Exists(visual) && text.Contains("<auto-generated>") ? visual : null;
        return new CodeDocument(path, text, newline, generatedFrom);
    }

    // How a script's text looks once loaded: \n line endings and spaces instead of tabs.
    public static string Normalize(string raw) =>
        raw.Replace("\r\n", "\n").Replace('\r', '\n').Replace("\t", new string(' ', IndentSize));

    public string Text => string.Join("\n", Lines);

    public void Save()
    {
        File.WriteAllText(Path, string.Join(Newline, Lines));
        _savedText = Text;
        DiskConflict = false;
        IgnoredDisk = null;
    }

    // The file changed on disk, by something else, while this copy has edits of its own: the user chooses which to keep.
    public bool DiskConflict { get; set; }
    public string? IgnoredDisk { get; set; }   // a version on disk the user chose not to load, so it isn't asked about again
    public string SavedText => _savedText;

    // Looks at the file as it is on disk now. A copy with no edits here is reloaded; one with edits is flagged (DiskConflict)
    // when the file differs from what was last loaded or saved, unless the user already chose to keep their version of it.
    public void CheckAgainstDisk()
    {
        if (!File.Exists(Path)) return;
        string disk = Normalize(File.ReadAllText(Path));
        if (!Dirty && disk != Text)
            Reload();
        else if (Dirty && disk != SavedText && disk != IgnoredDisk)
            DiskConflict = true;
    }

    // Replaces the text with what is on disk now, for a file changed outside the editor while it had no edits here.
    public void Reload()
    {
        string text = Normalize(File.ReadAllText(Path));
        Lines = Split(text);
        _savedText = text;
        _undo.Clear();
        _redo.Clear();
        DiskConflict = false;
        IgnoredDisk = null;
        Caret = Clamp(Caret);
        Anchor = null;
        Version++;
    }

    private static List<string> Split(string text) => text.Split('\n').ToList();

    // ---- selection --------------------------------------------------------------------

    public bool HasSelection => Anchor is { } a && a != Caret;

    public (TextPos Start, TextPos End) Selection
    {
        get
        {
            var a = Anchor ?? Caret;
            return a < Caret ? (a, Caret) : (Caret, a);
        }
    }

    public string SelectedText()
    {
        if (!HasSelection) return "";
        var (s, e) = Selection;
        if (s.Line == e.Line) return Lines[s.Line][s.Col..e.Col];
        var parts = new List<string> { Lines[s.Line][s.Col..] };
        for (int i = s.Line + 1; i < e.Line; i++) parts.Add(Lines[i]);
        parts.Add(Lines[e.Line][..e.Col]);
        return string.Join("\n", parts);
    }

    public void SelectAll()
    {
        Anchor = new TextPos(0, 0);
        Caret = new TextPos(Lines.Count - 1, Lines[^1].Length);
    }

    public void SelectWordAt(TextPos p)
    {
        p = Clamp(p);
        string line = Lines[p.Line];
        int start = p.Col, end = p.Col;
        while (start > 0 && IsWord(line[start - 1])) start--;
        while (end < line.Length && IsWord(line[end])) end++;
        Anchor = new TextPos(p.Line, start);
        Caret = new TextPos(p.Line, end);
    }

    public void MoveTo(TextPos p, bool extend)
    {
        p = Clamp(p);
        if (extend) Anchor ??= Caret;
        else Anchor = null;
        Caret = p;
        PreferredCol = -1;
    }

    public TextPos Clamp(TextPos p)
    {
        int line = Math.Clamp(p.Line, 0, Lines.Count - 1);
        return new TextPos(line, Math.Clamp(p.Col, 0, Lines[line].Length));
    }

    // ---- caret movement -----------------------------------------------------------------

    public void MoveLeft(bool word, bool extend)
    {
        if (HasSelection && !extend) { MoveTo(Selection.Start, false); return; }
        MoveTo(word ? WordLeft(Caret) : Step(Caret, -1), extend);
    }

    public void MoveRight(bool word, bool extend)
    {
        if (HasSelection && !extend) { MoveTo(Selection.End, false); return; }
        MoveTo(word ? WordRight(Caret) : Step(Caret, 1), extend);
    }

    public void MoveVertical(int lines, bool extend)
    {
        int col = PreferredCol >= 0 ? PreferredCol : Caret.Col;
        var target = Clamp(new TextPos(Caret.Line + lines, col));
        if (Caret.Line + lines < 0) target = new TextPos(0, 0);
        if (Caret.Line + lines >= Lines.Count) target = new TextPos(Lines.Count - 1, Lines[^1].Length);
        MoveTo(target, extend);
        PreferredCol = col;
    }

    // Home goes to the first non-space character, or to column 0 when already there.
    public void MoveHome(bool extend)
    {
        string line = Lines[Caret.Line];
        int indent = line.Length - line.TrimStart().Length;
        MoveTo(new TextPos(Caret.Line, Caret.Col == indent ? 0 : indent), extend);
    }

    public void MoveEnd(bool extend) => MoveTo(new TextPos(Caret.Line, Lines[Caret.Line].Length), extend);

    private TextPos Step(TextPos p, int delta)
    {
        if (delta < 0)
            return p.Col > 0 ? p with { Col = p.Col - 1 } : p.Line > 0 ? new TextPos(p.Line - 1, Lines[p.Line - 1].Length) : p;
        return p.Col < Lines[p.Line].Length ? p with { Col = p.Col + 1 } : p.Line < Lines.Count - 1 ? new TextPos(p.Line + 1, 0) : p;
    }

    private TextPos WordLeft(TextPos p)
    {
        if (p.Col == 0) return Step(p, -1);
        string line = Lines[p.Line];
        int c = p.Col;
        while (c > 0 && line[c - 1] == ' ') c--;
        if (c > 0 && IsWord(line[c - 1])) while (c > 0 && IsWord(line[c - 1])) c--;
        else if (c > 0) c--;
        return p with { Col = c };
    }

    private TextPos WordRight(TextPos p)
    {
        string line = Lines[p.Line];
        if (p.Col == line.Length) return Step(p, 1);
        int c = p.Col;
        while (c < line.Length && line[c] == ' ') c++;
        if (c < line.Length && IsWord(line[c])) while (c < line.Length && IsWord(line[c])) c++;
        else if (c < line.Length) c++;
        return p with { Col = c };
    }

    private static bool IsWord(char c) => char.IsLetterOrDigit(c) || c == '_';

    // ---- editing --------------------------------------------------------------------------

    // Replaces the selection (if any) with text, which may span lines.
    public void Insert(string text) => Edit(text.Length == 1 && text != "\n" ? EditKind.Typing : EditKind.Other, () => InsertRaw(text));

    // Types one character. A closing brace typed on an otherwise empty line lines up with its opening line.
    public void Type(char ch)
    {
        Edit(EditKind.Typing, () =>
        {
            if (ch == '}' && !HasSelection && Lines[Caret.Line].Trim().Length == 0)
            {
                int indent = Math.Max(0, Lines[Caret.Line].Length - IndentSize);
                Lines[Caret.Line] = new string(' ', indent);
                Caret = new TextPos(Caret.Line, indent);
            }
            InsertRaw(ch.ToString());
        });
    }

    // Enter keeps the current indentation, indents after '{', and moves a following '}' to its own line.
    public void NewLine()
    {
        Edit(EditKind.Other, () =>
        {
            DeleteSelectionRaw();
            string line = Lines[Caret.Line];
            string indent = new string(' ', line.Length - line.TrimStart().Length);
            string before = line[..Caret.Col].TrimEnd();
            string after = line[Caret.Col..];
            bool opens = before.EndsWith('{');
            bool closes = after.TrimStart().StartsWith('}');

            string inner = opens ? indent + new string(' ', IndentSize) : indent;
            Lines[Caret.Line] = line[..Caret.Col].TrimEnd();
            if (opens && closes)
            {
                Lines.Insert(Caret.Line + 1, inner);
                Lines.Insert(Caret.Line + 2, indent + after.TrimStart());
            }
            else
                Lines.Insert(Caret.Line + 1, inner + after.TrimStart());
            Caret = new TextPos(Caret.Line + 1, inner.Length);
        });
    }

    public void Backspace()
    {
        Edit(EditKind.Deleting, () =>
        {
            if (DeleteSelectionRaw()) return;
            if (Caret.Col == 0)
            {
                if (Caret.Line == 0) return;
                int col = Lines[Caret.Line - 1].Length;
                Lines[Caret.Line - 1] += Lines[Caret.Line];
                Lines.RemoveAt(Caret.Line);
                Caret = new TextPos(Caret.Line - 1, col);
                return;
            }
            // In leading whitespace, delete back to the previous indent stop.
            string line = Lines[Caret.Line];
            int remove = 1;
            if (line[..Caret.Col].Trim().Length == 0)
                remove = (Caret.Col - 1) % IndentSize + 1;
            Lines[Caret.Line] = line.Remove(Caret.Col - remove, remove);
            Caret = Caret with { Col = Caret.Col - remove };
        });
    }

    public void Delete()
    {
        Edit(EditKind.Deleting, () =>
        {
            if (DeleteSelectionRaw()) return;
            string line = Lines[Caret.Line];
            if (Caret.Col < line.Length)
                Lines[Caret.Line] = line.Remove(Caret.Col, 1);
            else if (Caret.Line < Lines.Count - 1)
            {
                Lines[Caret.Line] = line + Lines[Caret.Line + 1];
                Lines.RemoveAt(Caret.Line + 1);
            }
        });
    }

    // Tab inserts spaces to the next indent stop, or indents every selected line. Shift+Tab outdents.
    public void Indent(bool outdent)
    {
        bool lines = outdent || (HasSelection && Selection.Start.Line != Selection.End.Line);
        Edit(EditKind.Other, () =>
        {
            if (!outdent && !(HasSelection && Selection.Start.Line != Selection.End.Line))
            {
                DeleteSelectionRaw();
                InsertRaw(new string(' ', IndentSize - Caret.Col % IndentSize));
                return;
            }
            var (s, e) = HasSelection ? Selection : (Caret, Caret);
            int last = e.Col == 0 && e.Line > s.Line ? e.Line - 1 : e.Line;
            int caretShift = 0, anchorShift = 0;
            for (int i = s.Line; i <= last; i++)
            {
                string line = Lines[i];
                int shift;
                if (outdent)
                {
                    shift = -Math.Min(IndentSize, line.Length - line.TrimStart().Length);
                    Lines[i] = line[-shift..];
                }
                else
                {
                    shift = line.Length == 0 ? 0 : IndentSize;
                    if (shift > 0) Lines[i] = new string(' ', IndentSize) + line;
                }
                if (i == Caret.Line) caretShift = shift;
                if (Anchor is { } a && i == a.Line) anchorShift = shift;
            }
            Caret = Clamp(Caret with { Col = Math.Max(0, Caret.Col + caretShift) });
            if (Anchor is { } anchor) Anchor = Clamp(anchor with { Col = Math.Max(0, anchor.Col + anchorShift) });
        }, keepSelection: lines);
    }

    // Cmd/Ctrl+/ comments out the selected lines with //, or uncomments them when all are commented.
    public void ToggleComment()
    {
        Edit(EditKind.Other, () =>
        {
            var (s, e) = HasSelection ? Selection : (Caret, Caret);
            int last = e.Col == 0 && e.Line > s.Line ? e.Line - 1 : e.Line;
            var range = Enumerable.Range(s.Line, last - s.Line + 1).Where(i => Lines[i].Trim().Length > 0).ToList();
            if (range.Count == 0) return;
            bool uncomment = range.All(i => Lines[i].TrimStart().StartsWith("//"));
            int indent = range.Min(i => Lines[i].Length - Lines[i].TrimStart().Length);
            foreach (int i in range)
            {
                string line = Lines[i];
                if (uncomment)
                {
                    int at = line.IndexOf("//", StringComparison.Ordinal);
                    int len = at + 2 < line.Length && line[at + 2] == ' ' ? 3 : 2;
                    Lines[i] = line.Remove(at, len);
                }
                else
                    Lines[i] = line.Insert(indent, "// ");
            }
            Caret = Clamp(Caret);
            if (Anchor is { } a) Anchor = Clamp(a);
        }, keepSelection: true);
    }

    public void Undo() => Restore(_undo, _redo);
    public void Redo() => Restore(_redo, _undo);

    private void Restore(List<Snapshot> from, List<Snapshot> to)
    {
        if (ReadOnly || from.Count == 0) return;
        to.Add(new Snapshot(Text, Caret));
        var snap = from[^1];
        from.RemoveAt(from.Count - 1);
        Lines = Split(snap.Text);
        Caret = Clamp(snap.Caret);
        Anchor = null;
        _lastKind = EditKind.None;
        Version++;
    }

    // Records an undo step (merging runs of typing or deleting), applies the change and bumps the version.
    // keepSelection is for line operations (indent, comment), so they can be repeated on the same lines.
    private void Edit(EditKind kind, Action change, bool keepSelection = false)
    {
        if (ReadOnly) return;
        string before = Text;
        var caretBefore = Caret;
        long now = Environment.TickCount64;
        bool merge = kind == _lastKind && kind is EditKind.Typing or EditKind.Deleting &&
                     now - _lastEditTicks < GroupMilliseconds && _undo.Count > 0;

        change();
        if (Text == before) return;

        if (!merge) _undo.Add(new Snapshot(before, caretBefore));
        if (_undo.Count > 500) _undo.RemoveAt(0);
        _redo.Clear();
        _lastKind = kind;
        _lastEditTicks = now;
        if (!keepSelection) Anchor = null;
        PreferredCol = -1;
        Version++;
    }

    private void InsertRaw(string text)
    {
        DeleteSelectionRaw();
        string line = Lines[Caret.Line];
        string head = line[..Caret.Col], tail = line[Caret.Col..];
        var parts = text.Split('\n');
        if (parts.Length == 1)
        {
            Lines[Caret.Line] = head + text + tail;
            Caret = Caret with { Col = Caret.Col + text.Length };
            return;
        }
        Lines[Caret.Line] = head + parts[0];
        for (int i = 1; i < parts.Length; i++)
            Lines.Insert(Caret.Line + i, parts[i] + (i == parts.Length - 1 ? tail : ""));
        Caret = new TextPos(Caret.Line + parts.Length - 1, parts[^1].Length);
    }

    private bool DeleteSelectionRaw()
    {
        if (!HasSelection) return false;
        var (s, e) = Selection;
        Lines[s.Line] = Lines[s.Line][..s.Col] + Lines[e.Line][e.Col..];
        Lines.RemoveRange(s.Line + 1, e.Line - s.Line);
        Caret = s;
        Anchor = null;
        return true;
    }
}
